import java.util.Scanner; // Импортируем класс Scanner из стандартной библиотеки для чтения ввода из консоли

// Объявляем публичный класс с именем Calculator
public class Calculator {

    // Объявляем приватное перечисление InputType для обозначения типов результата при вводе данных
    private enum InputType {
        // Вариант перечисления: пользователь ввел корректное число
        NUMBER,
        // Вариант перечисления: пользователь ввел команду сброса 'C'
        CLEAR,
        // Вариант перечисления: пользователь ввел команду выключения 'S'
        STOP,
        // Вариант перечисления: поток ввода неожиданно завершился (End of File)
        EOF
    }

    // Объявляем приватную неизменяемую запись (record) для хранения типа результата и числового значения
    private record InputResult(InputType type, double value) {
        // Объявляем статический метод, который создает и возвращает объект InputResult с введенным числом
        static InputResult number(double value) {
            // Возвращаем новый экземпляр InputResult с типом NUMBER и переданным числом
            return new InputResult(InputType.NUMBER, value);
        }

        // Объявляем статический метод, возвращающий объект с сигналом сброса расчетов
        static InputResult clear() {
            // Возвращаем новый экземпляр InputResult с типом CLEAR и значением Double.NaN
            return new InputResult(InputType.CLEAR, Double.NaN);
        }

        // Объявляем статический метод, возвращающий объект с сигналом остановки программы
        static InputResult stop() {
            // Возвращаем новый экземпляр InputResult с типом STOP и значением Double.NaN
            return new InputResult(InputType.STOP, Double.NaN);
        }

        // Объявляем статический метод, возвращающий объект с сигналом о закрытии потока ввода
        static InputResult eof() {
            // Возвращаем новый экземпляр InputResult с типом EOF и значением Double.NaN
            return new InputResult(InputType.EOF, Double.NaN);
        }
    }

    // Объявляем главный метод main — точку входа в программу
    public static void main(String[] args) {
        // Создаем объект Scanner для считывания потока ввода из консоли (System.in)
        Scanner scanner = new Scanner(System.in);

        // Выводим в консоль приветственное сообщение и список доступных управляющих команд
        System.out.println("Калькулятор запущен. Справочно: команды (доступны на любом шаге): C — сброс, S — выключение.");

        // Главный бесконечный цикл приложения: отвечает за глобальный перезапуск калькулятора после сброса (команда C)
        while (true) {
            // Вызываем метод readInput для считывания первого числа или управляющих команд C / S
            InputResult firstInput = readInput(scanner, "Введите первое число (или команду C / S): ");

            // Проверяем, не завершился ли поток ввода при чтении первого числа
            if (firstInput.type() == InputType.EOF) {
                // Выводим информационное сообщение в консоль о завершении ввода
                System.out.println("Ввод закончился. Выключение.");
                // Завершаем работу метода main и всей программы
                return;
            }

            // Проверяем, не ввел ли пользователь команду выключения 'S' ('s') вместо первого числа
            if (firstInput.type() == InputType.STOP) {
                // Выводим прощальное сообщение в консоль
                System.out.println("Завершение работы калькулятора. Хорошего дня!");
                // Завершаем работу метода main и всей программы
                return;
            }

            // Проверяем, не ввел ли пользователь команду сброса 'C' ('c') вместо первого числа
            if (firstInput.type() == InputType.CLEAR) {
                // Выводим уведомление о сбросе состояния в консоль
                System.out.println("Сброс. Начинаем новый расчет.");
                // Переходим к следующей итерации главного цикла для повторного запроса первого числа
                continue;
            }

            // Записываем полученное корректное первое число в переменную result
            double result = firstInput.value();

            // Внутренний бесконечный рабочий цикл: обрабатывает цепочку последовательных операций с текущим результатом
            while (true) {
                // Выводим приглашение для ввода оператора или команды
                System.out.print("Введите оператор (+ - * /) или команду (C — сброс, S — выключение): ");

                // Проверяем, открыт ли еще поток ввода перед попыткой считать оператор
                if (!scanner.hasNext()) {
                    // Выводим информационное сообщение о закрытии потока ввода
                    System.out.println("Ввод закончился. Выключение.");
                    // Немедленно завершаем работу программы
                    return;
                }

                // Считываем из консоли следующее введенное слово (токен) в виде строки
                String token = scanner.next();

                // Берем первый символ строки, переводим его в верхний регистр для поддержки команд 'c'/'s' и записываем в char
                char operation = Character.toUpperCase(token.charAt(0));

                // Проверяем, что введена строка длиной 1 символ и это команда сброса 'C'
                if (token.length() == 1 && operation == 'C') {
                    // Выводим уведомление о сбросе состояния в консоль
                    System.out.println("Сброс. Начинаем новый расчет.");
                    // Прерываем текущий (внутренний) цикл while, возвращаясь в главный цикл для ввода нового первого числа
                    break;
                }

                // Проверяем, что введена строка длиной 1 символ и это команда выключения 'S'
                if (token.length() == 1 && operation == 'S') {
                    // Выводим прощальное сообщение в консоль
                    System.out.println("Завершение работы калькулятора. Хорошего дня!");
                    // Полностью выходим из метода main, завершая работу всего приложения
                    return;
                }

                // Конструкция switch для проверки введенного символа математической операции
                switch (operation) {
                    // Проверяем, что введён один из поддерживаемых математических операторов
                    case '+', '-', '*', '/' -> {
                        // Проверяем, что пользователь ввел ровно один символ (а не слово начинающееся с оператора и т.п.)
                        if (token.length() != 1) {
                            // Выводим сообщение об ошибке с указанием некорректного ввода
                            System.out.println("Ошибка: неподдерживаемая операция '" + token + "'.");
                            // Напоминаем текущее сохраненное значение результата
                            System.out.println("Результат не изменён: " + result);
                            // Переходим на следующую итерацию внутреннего цикла для повторного ввода оператора
                            continue;
                        }

                        // Запрашиваем у пользователя второе число или вызов управляющей команды C / S
                        InputResult secondInput = readInput(scanner, "Введите второе число (или команду C / S): ");

                        // Проверяем, не оборвался ли поток данных при вводе второго числа
                        if (secondInput.type() == InputType.EOF) {
                            // Выводим сообщение в консоль о завершении ввода
                            System.out.println("Ввод закончился. Выключение.");
                            // Немедленно завершаем программу
                            return;
                        }

                        // Проверяем, не ввел ли пользователь команду выключения 'S' вместо второго числа
                        if (secondInput.type() == InputType.STOP) {
                            // Выводим прощальное сообщение в консоль
                            System.out.println("Завершение работы калькулятора. Хорошего дня!");
                            // Немедленно завершаем программу
                            return;
                        }

                        // Проверяем, не ввел ли пользователь команду сброса 'C' вместо второго числа
                        if (secondInput.type() == InputType.CLEAR) {
                            // Выводим уведомление о сбросе состояния в консоль
                            System.out.println("Сброс. Начинаем новый расчет.");
                            // Устанавливаем result в Double.NaN как маркер необходимости прервать внутренний цикл
                            result = Double.NaN;
                            // Выходим из блока switch
                            break;
                        }

                        // Вычисляем новый результат, передав операцию, текущее значение и второй операнд в метод apply
                        result = apply(operation, result, secondInput.value());
                    }

                    // Ветка по умолчанию: срабатывает, если пользователь ввел некорректный символ (не +, -, *, /, C, S)
                    default -> {
                        // Выводим сообщение об ошибке с указанием того некорректного текста, который ввел пользователь
                        System.out.println("Ошибка: неподдерживаемая операция '" + token + "'.");
                        // Напоминаем текущее сохраненное значение
                        System.out.println("Результат не изменён: " + result);
                        // Переходим на следующую итерацию рабочего цикла, пропуская вывод строки "Результат: ..." ниже
                        continue;
                    }
                }

                // Проверяем, не был ли установлен маркер сброса Double.NaN при вводе второго числа
                if (Double.isNaN(result)) {
                    // Прерываем внутренний цикл while и возвращаемся к вводу нового первого числа
                    break;
                }

                // Выводим на экран актуальный результат после успешного расчета
                System.out.println("Результат: " + result);
            }
        }
    }

    // Объявляем приватный вспомогательный метод для безопасного чтения чисел и управляющих команд (C и S)
    private static InputResult readInput(Scanner scanner, String prompt) {
        // Бесконечный цикл внутри метода: повторяется до тех пор, пока пользователь не введет корректное число или команду
        while (true) {
            // Выводим переданный текст-приглашение (пример - "Введите первое число: ")
            System.out.print(prompt);

            // Проверяем, открыт ли вообще поток ввода (если ввод неожиданно завершился)
            if (!scanner.hasNext()) {
                // Возвращаем объект InputResult с типом EOF как сигнал о завершении ввода
                return InputResult.eof();
            }

            // Проверяем, можно ли распознать то, что ввел пользователь, как число double
            if (scanner.hasNextDouble()) {
                // Считываем это число, оборачиваем в InputResult и возвращаем из метода
                return InputResult.number(scanner.nextDouble());
            }

            // Если введено не число, считываем этот некорректный текст в переменную token, очищая буфер
            String token = scanner.next();
            // Проверяем, ввел ли пользователь команду сброса 'C' (без учета регистра)
            if (token.equalsIgnoreCase("C")) {
                // Возвращаем объект InputResult с типом CLEAR
                return InputResult.clear();
            }

            // Проверяем, ввел ли пользователь команду выключения 'S' (без учета регистра)
            if (token.equalsIgnoreCase("S")) {
                // Возвращаем объект InputResult с типом STOP
                return InputResult.stop();
            }

            // Выводим сообщение об ошибке ввода, если текст не является ни числом, ни командой C/S
            System.out.println("Ошибка: '" + token + "' — не число и не команда (C/S), попробуйте ещё раз.");
        }
    }

    // Объявляем метод, который определяет, какой именно математический метод нужно вызвать для проведения расчетов
    private static double apply(char operation, double current, double operand) {
        // Используем switch expression для возврата значения напрямую из ветвей switch
        return switch (operation) {
            // Если операция '+', вызываем метод summation и возвращаем его результат
            case '+' -> summation(current, operand);
            // Если операция '-', вызываем метод subtraction и возвращаем его результат
            case '-' -> subtraction(current, operand);
            // Если операция '*', вызываем метод multiplication и возвращаем его результат
            case '*' -> multiplication(current, operand);
            // Если операция '/', вызываем метод division (в котором также имеется проверка деления на ноль)
            case '/' -> division(current, operand);
            // Защита от некорректных операций: возвращает текущее число, если управление передано неверно
            default -> current;
        };
    }

    // Вспомогательный приватный метод для сложения: возвращает сумму a и b
    private static double summation(double a, double b) {
        return a + b;
    }

    // Вспомогательный приватный метод для вычитания: возвращает разность a и b
    private static double subtraction(double a, double b) {
        return a - b;
    }

    // Вспомогательный приватный метод для умножения: возвращает произведение a и b
    private static double multiplication(double a, double b) {
        return a * b;
    }

    // Вспомогательный приватный метод для деления: возвращает частное от деления a на b
    private static double division(double a, double b) {
        // Проверяем, не равен ли делитель нулю
        if (b == 0) {
            // Выводим сообщение об ошибке при попытке деления на ноль
            System.out.println("Ошибка: делить на ноль нельзя!");
            // Возвращаем исходное делимое без изменений
            return a;
        }
        // Выполняем деление a на b и возвращаем результат
        return a / b;
    }
}